CANARY_CHURN = """\
import gc

# Every generation creates a fresh function from its own code object,
# executes it in machine code, drops the last reference and collects.  The
# execute surface takes only exact positional arguments and a body of
# whitelisted opcodes, so the workload is written that way; a default
# argument would make every generation a refusal instead of a lifecycle.
_source = (
    "def churn_{i}(a, b, one):\\n"
    "    total = a - a\\n"
    "    i = total\\n"
    "    while i < b:\\n"
    "        total = total + a\\n"
    "        i = i + one\\n"
    "    return total\\n"
)
_compiled = 0
_generations = 400
for _gen in range(_generations):
    _ns = {}
    exec(_source.format(i=_gen), _ns)
    _fn = _ns["churn_%d" % _gen]
    assert cinderjit.force_compile(_fn) is True, _gen
    _compiled += 1
    _before = _cinderx._get_trigger_stats()["machine_code_entries"]
    for _ in range(4):
        assert _fn(3, 5, 1) == 15, _gen
    _delta = _cinderx._get_trigger_stats()["machine_code_entries"] - _before
    # Every generation must run compiled, not just the first: a
    # whole-process counter would stay satisfied while the remaining
    # generations quietly fell back to the interpreter.
    assert _delta == 4, (_gen, _delta)
    del _ns
    del _fn
    gc.collect()
    # The registry must stay readable after each death: a dead function
    # left behind as a borrowed pointer shows up here first.
    for _live in cinderjit.get_compiled_functions():
        assert _live.__qualname__, _live

assert _compiled == _generations, (_compiled, _generations)
_leftover = [f.__qualname__ for f in cinderjit.get_compiled_functions()
             if f.__qualname__.startswith("churn_")]
assert not _leftover, _leftover
"""


# MR-05 lifecycle exercises: each drives a watcher-less death path and
# asserts via the notification counters that the JIT was actually told.
LIFECYCLE_PRELUDE = """\
import gc
import _cinderx


def _notifications():
    stats = _cinderx._get_trigger_stats()
    return (
        stats["function_destroyed_notifications"],
        stats["code_destroyed_notifications"],
    )


def _make_plain(name, body="    return x + 1\\n"):
    ns = {}
    exec("def %s(x):\\n%s" % (name, body), ns)
    # Pop it from its own globals, or every subject sits in a cycle and
    # the exercise measures the collector instead of the notification.
    return ns.pop(name)


def _compile_fresh(name, body="    return x + 1\\n"):
    fn = _make_plain(name, body)
    assert cinderjit.force_compile(fn) is True, name
    return fn
"""

# function_churn: plain functions, created, compiled, executed, dropped.
LIFECYCLE_FUNCTION_CHURN = """\
_funcs, _codes = _notifications()
for _i in range(2000):
    _fn = _compile_fresh("churned_%d" % _i)
    assert _fn(1) == 2
    del _fn
    # No collection: with no cycle and no registry owning it, the function
    # has to die on that line.  One death per generation is what makes a
    # retained reference visible instead of merely delayed.
    assert _notifications()[0] - _funcs == _i + 1, _i
_after_funcs, _after_codes = _notifications()
assert _after_funcs - _funcs == 2000, (_funcs, _after_funcs)
assert _after_codes - _codes >= 2000, (_codes, _after_codes)
assert not [f for f in cinderjit.get_compiled_functions()
            if f.__qualname__.startswith("churned_")]
assert cinderjit._get_resident_compiled_functions() == 0
"""

# closure_churn: 2k cell-carrying closures plus 2k lambdas, each arm
# compiling generation after generation against one shared code object.
# The closure arm used to assert refusal, but MR-07's pass rework put
# LOAD_DEREF/COPY_FREE_VARS bodies on the execute surface for real, so
