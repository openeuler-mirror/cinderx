# that types them immortal skips reference counting and drains them until
# bool_dealloc runs -- the regression the singleton-lifetime fix closed.
# The general refcount matrix deliberately excludes the pseudo-immortal
# singletons from drift judgment, which excludes exactly this class, so
# they get their own gate: machine code exercises every whitelisted
# singleton-producing path and their reference counts must not drift.
SINGLETON_LIFETIME = """\
import sys

_source = (
    "def churn(x, one):\\n"
    "    t = x < one\\n"
    "    f = not t\\n"
    "    same = t is f\\n"
    "    n = None\\n"
    "    m = n is None\\n"
    "    if m:\\n"
    "        return same\\n"
    "    return t\\n"
)
_ns = {}
exec(_source, _ns)
_fn = _ns.pop("churn")
assert cinderjit.force_compile(_fn) is True
assert _fn(1, 2) is False

_ITERS = 10000
# Settle allocator state, then measure a window of identical length; a
# machine-code path that leaks or over-releases a singleton drifts by the
# iteration count, dwarfing any ambient jitter.
for _ in range(_ITERS):
    _fn(1, 2)
    _fn(2, 1)
_before = (
    sys.getrefcount(True), sys.getrefcount(False), sys.getrefcount(None))
for _ in range(_ITERS):
    _fn(1, 2)
    _fn(2, 1)
_after = (
    sys.getrefcount(True), sys.getrefcount(False), sys.getrefcount(None))
_drift = [abs(a - b) for a, b in zip(_after, _before)]
assert max(_drift) <= 16, (_before, _after)
"""


