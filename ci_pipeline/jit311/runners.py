def unify(fields_path: str, out_path: str) -> int:
    """Assemble the unified run report as a real artifact: a fresh gate
    child supplies the runtime snapshot, the libtest leg's emission
    supplies the module surface, and strict validation refuses any field
    that is missing or null."""
    spec = cold_compile_runner()
    result = run(spec)
    if not result.ok or result.report is None:
        for err in result.errors:
            print(f"unified-report: gate child failed: {err}")
        return 1
    unified = dict(result.report)
    unified["target_modules_attempted"] = None
    unified["worker_crashes"] = None
    try:
        fields = json.loads(Path(fields_path).read_text())
    except OSError as exc:
        print(f"unified-report: cannot read leg emission: {exc}")
        return 1
    foreign = set(fields) - {"target_modules_attempted", "worker_crashes"}
    if foreign:
        print(f"unified-report: leg emitted non-leg fields: {foreign}")
        return 1
    unified.update(fields)
    errors = _report.validate_schema(unified, strict=True)
    frozen = len(load_libtest_target_manifest())
    if not errors:
        if unified["target_modules_attempted"] != frozen:
            errors.append(
                f"target_modules_attempted must equal the frozen manifest "
                f"({frozen}), got {unified['target_modules_attempted']}"
            )
        if unified["worker_crashes"] != 0:
            errors.append(
                f"worker_crashes must be zero, got "
                f"{unified['worker_crashes']}"
            )
    if errors:
        for err in errors:
            print(f"unified-report: {err}")
        return 1
    Path(out_path).write_text(
        json.dumps(unified, indent=1, sort_keys=True) + "\n"
    )
    print(
        f"unified-report: all fields strictly typed, "
        f"target_modules_attempted="
        f"{unified['target_modules_attempted']}"
    )
    return 0


def run_all(python: str | None = None) -> list[RunResult]:
    """Run the stage-default suite: MR-03 shadow expectations plus the
    MR-04 canary execution drivers."""
    specs: list[RunnerSpec] = [
        cold_compile_runner(),
        warm_compile_runner(),
        auto_like_runner(),
        shadow_compile_runner(),
        lifecycle_churn_runner(),
        stdlib_shadow_runner(),
        corpus_shadow_runner(),
        dynamic_shapes_runner(),
    ]
    specs += [
        canary_force_cold_runner(),
        canary_force_warm_runner(),
        canary_execute_runner(),
        exception_semantics_runner(),
        stdlib_canary_runner(),
        canary_churn_runner(),
        singleton_lifetime_runner(),
    ]
    specs += lifecycle_runners()
    specs += shutdown_repetition_runner()
    specs += canary_shutdown_runner()
    specs += config_matrix_runner()
    results = [run(spec, python=python) for spec in specs]
    return results


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--unify" in argv:
        try:
            fields_path = argv[argv.index("--unify") + 1]
            out_path = argv[argv.index("-o") + 1]
        except (ValueError, IndexError):
            print("usage: runners --unify <fields.json> -o <out.json>")
            return 2
        return unify(fields_path, out_path)
    # `--pyperf` is a prefix of `--pyperformance-all`; dispatch on exact
    # tokens, and handle the full applicable set first so the daily job
    # cannot silently shrink to the 33-name tranche.
    if "--pyperformance-all" in argv:
        spec = pyperformance_completeness_runner(
            benchmarks=discover_all_pyperf_benchmarks()
        )
        if spec is None:
            print(
                "jit311-runners: pyperformance is required for the daily "
                "shadow gate",
                file=sys.stderr,
            )
            return 2
        result = run(spec)
        print(result.summary())
        return 0 if result.ok else 1
    if "--stdlib-canary" in argv:
        result = run(stdlib_canary_runner())
        print(result.summary())
        if result.report is not None:
            keys = (
                "compile_requests",
                "compile_installed",
                "compile_rejected",
                "machine_code_entries",
                "machine_code_installed",
                "compiled_function_creations",
                "unknown_rejects",
                "organic_deopt_hits",
                "forced_deopt_hits",
                "target_modules_attempted",
                "live_compiled_functions_at_exit",
            )
            for key in keys:
                print("%s=%r" % (key, result.report.get(key)))
        return 0 if result.ok else 1
    if "--pyperf-canary" in argv:
        # The canary leg runs the committed tranche, not the full applicable
        # set the shadow daily covers: every benchmark here compiles and
        # executes machine code, which the nightly budget cannot absorb for
        # the whole set.  Say so out loud -- a bounded run that reads as
        # full coverage is how a gate starts lying.
        canary_names = load_pyperf_benchmarks()
        # The cap is deliberate, so it is stated as a fact the leg checks
        # rather than a line it prints.  Swallowing a discovery failure
        # would delete the "of N applicable" half and let a bounded run
        # read as full coverage.
        discoverable = len(discover_all_pyperf_benchmarks())
        if not discoverable:
            print(
                "jit311-runners: pyperformance reported no applicable "
                "benchmarks; the canary coverage claim cannot be checked",
                file=sys.stderr,
            )
            return 1
        if len(canary_names) > discoverable:
            print(
                f"jit311-runners: the canary tranche ({len(canary_names)}) "
                f"exceeds the applicable set ({discoverable})",
                file=sys.stderr,
            )
            return 1
        print(
            f"jit311-runners: canary completion leg covers "
            f"{len(canary_names)} of {discoverable} applicable benchmark(s); "
            f"the remainder is covered by the shadow completeness leg"
        )
        spec = pyperformance_completeness_runner(
            mode="canary", benchmarks=list(canary_names)
        )
        if spec is None:
            print(
                "jit311-runners: pyperformance is not provisioned in this "
                "environment; the canary completion leg cannot run",
                file=sys.stderr,
            )
            return 1
        result = run(spec)
        print(result.summary())
        return 0 if result.ok else 1
    if "--pyperf" in argv:
        spec = pyperformance_completeness_runner(
            benchmarks=list(load_pyperf_benchmarks())
        )
        if spec is None:
            print(
                "jit311-runners: pyperformance is not provisioned in this "
                "environment; the completeness leg cannot run (provision "
                "the runner venv with the pinned pyperformance package)",
                file=sys.stderr,
            )
            return 1
        result = run(spec)
        print(result.summary())
        return 0 if result.ok else 1
    if "--shadow-surface" in argv:
        from ci_pipeline.jit311.shadow_surface import main as surface_main

        rest = [arg for arg in argv if arg != "--shadow-surface"]
        return surface_main(rest)

    results = run_all()
    failed = [r for r in results if not r.ok]
    for result in results:
        print(result.summary())
    print(
        f"jit311-runners: {len(results) - len(failed)}/{len(results)} passed"
    )
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
