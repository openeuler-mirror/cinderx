# Judges

def expect(field_name: str, op: str, value: int) -> Judge:
    """Field comparison judge: op is one of ==, >, >=."""

    def judge(snap: dict) -> list[str]:
        actual = snap.get(field_name)
        checks = {
            "==": actual == value,
            ">": isinstance(actual, int) and actual > value,
            ">=": isinstance(actual, int) and actual >= value,
        }
        if not checks[op]:
            return [f"expected {field_name} {op} {value}, got {actual!r}"]
        return []

    return judge


def _validate_report_schema(snap: dict) -> list[str]:
    # Import lazily so importing this driver remains side-effect free in the
    # parent process.
    from ci_pipeline.jit311.report import validate_schema

    return validate_schema(snap)


def requests_accounted() -> Judge:
    """Every recorded request must be either compiled or stably refused."""

    def judge(snap: dict) -> list[str]:
        requested = snap.get("compile_requests")
        accounted = snap.get("compile_success", 0) + snap.get(
            "compile_rejected", 0
        )
        if requested != accounted:
            return [
                "compile requests are not fully accounted: "
                f"requests={requested!r}, success+rejected={accounted!r}"
            ]
        return []

    return judge


def canary_requests_accounted() -> Judge:
    """Canary answers a request by installing machine code, so the ledger
    closes through compile_installed rather than the shadow counter."""

    def judge(snap: dict) -> list[str]:
        requested = snap.get("compile_requests")
        accounted = snap.get("compile_installed", 0) + snap.get(
            "compile_rejected", 0
        )
        if requested != accounted:
            return [
                "compile requests are not fully accounted: "
                f"requests={requested!r}, installed+rejected={accounted!r}"
            ]
        return []

    return judge


def evaluator_is_installed(snap: dict) -> list[str]:
    if snap.get("evaluator_installed") is not True:
        return [
            "expected evaluator_installed is True, got "
            f"{snap.get('evaluator_installed')!r}"
        ]
    return []


def gate_holds() -> list[Judge]:
    """The capability-gate default: nothing compiled, nothing executed,
    no unknown refusals."""
    return [
        evaluator_is_installed,
        expect("executable_alloc_calls", "==", 0),
        expect("executable_alloc_bytes", "==", 0),
        expect("compiled_function_creations", "==", 0),
        expect("machine_code_entries", "==", 0),
        expect("machine_code_installed", "==", 0),
        expect("forced_deopt_hits", "==", 0),
        expect("organic_deopt_hits", "==", 0),
        expect("events_dropped", "==", 0),
        expect("supported_opcode_failures", "==", 0),
        expect("unknown_rejects", "==", 0),
        expect("live_compiled_functions_at_exit", "==", 0),
        expect("worker_crashes", "==", 0),
    ]


def shadow_holds(*, require_specialized: bool = False) -> list[Judge]:
    """A real shadow compile completed, but no executable state escaped."""
    judges = gate_holds() + [
        expect("compile_requests", ">", 0),
        expect("compile_success", ">", 0),
        expect("shadow_codegen_bytes", ">", 0),
        expect("peak_rss_bytes", ">", 0),
        requests_accounted(),
    ]
    if require_specialized:
        judges.append(expect("specialized_opcodes_consumed", ">", 0))
    return judges


